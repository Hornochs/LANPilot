#!/usr/bin/env python3
"""Write packaging/requirements.txt: the runtime dependencies the packages ship, pinned to
exact versions and to the SHA-256 of every file PyPI has for them.

The distribution packages contain a Python environment built in CI. Without this file,
that environment would get whatever PyPI serves at build time; with it, a release installs
exactly what was reviewed (``pip install --require-hashes``), and Dependabot proposes
updates to it as pull requests.

The dependencies are resolved by installing LANPilot from this checkout into a fresh
virtual environment with this interpreter, so run it with a supported Python (3.11-3.13
resolve to the same set; see docs/architecture.md, "Packaging").

Usage: python3 scripts/lock_requirements.py
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "packaging/requirements.txt"
HEADER = """\
# Runtime dependencies of the distribution packages, with the hash of every file on PyPI.
# Generated by scripts/lock_requirements.py from pyproject.toml; do not edit by hand.
# packaging/build.sh installs them with --require-hashes.
"""


def resolve() -> list[tuple[str, str]]:
    """Name and version of every runtime dependency, as pip resolves them today."""
    with tempfile.TemporaryDirectory() as directory:
        venv = Path(directory) / "venv"
        # Fixed commands with paths this script chose.
        subprocess.run([sys.executable, "-m", "venv", str(venv)], check=True)  # noqa: S603
        python = str(venv / "bin/python")
        install = [python, "-m", "pip", "install", "--quiet", str(ROOT)]
        subprocess.run(install, check=True)  # noqa: S603
        listing = subprocess.run(  # noqa: S603
            [python, "-m", "pip", "list", "--format=json", "--exclude-editable"],
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    skip = {"pip", "lanpilot"}
    return sorted(
        (item["name"].lower(), item["version"])
        for item in json.loads(listing)
        if item["name"].lower() not in skip
    )


def hashes(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as response:
        release = json.load(response)
    digests = sorted({file["digests"]["sha256"] for file in release["urls"]})
    if not digests:
        raise SystemExit(f"PyPI lists no files for {name} {version}")
    return digests


def main() -> None:
    lines = [HEADER]
    for name, version in resolve():
        entry = [f"{name}=={version}"]
        entry += [f"    --hash=sha256:{digest}" for digest in hashes(name, version)]
        lines.append(" \\\n".join(entry) + "\n")
    TARGET.write_text("".join(lines))
    print(f"wrote {TARGET.relative_to(ROOT)}")  # noqa: T201 - command line tool


if __name__ == "__main__":
    main()
